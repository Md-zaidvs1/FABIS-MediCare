const createBlankTeethMap = (): Record<number, ToothRecord> => {
  const map: Record<number, ToothRecord> = {};
  for (let i = 1; i <= 32; i++) {
    map[i] = {
      toothNumber: i,
      fdiNumber: universalToFDI(i),
      name: getToothName(i),
      condition: 'Healthy',
    };
  }
  return map;
};

